"""Build, for each provider, the OPA bundle its connector would serve after every
offer was bought once, and the Rego tests of each offer's class.

    python -m tests.opa.build --pap http://localhost:18080 --out tests/opa/out

Needs an empty odrl-pap (the version deployed in the connectors) at --pap; run.sh
starts one. For each provider: every offer gets its own buyer (order), the policy
goes in exactly as contract-management sends it (rulebook_gen.order), then the
three bundles (policies, methods, data) are downloaded to out/<provider>/ and
out/<provider>/cases_test.rego is written. `opa test out/<provider>` runs them.
"""

import argparse
import base64
import io
import json
import pathlib
import re
import shutil
import tarfile
import urllib.request

from rulebook_gen.__main__ import generate, load_offers
from rulebook_gen.order import instantiate
from rulebook_gen.policies import ROLE_TARGET

from .cases import CASES

STRANGER = "did:web:stranger.example"


def buyer_of(offer_name):
    return f"did:web:buyer-{offer_name}.example"


def _b64(data):
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def token(issuer, cred_type, roles):
    """An unsigned-but-well-formed JWT like the verifier's: OPA only decodes it
    (the signature is checked by APISIX before OPA is asked)."""
    payload = {
        "verifiableCredential": {
            "issuer": issuer,
            "type": ["VerifiableCredential", cred_type],
            "credentialSubject": {"roles": [{"target": ROLE_TARGET, "names": roles}]},
        }
    }
    header = {"alg": "ES256", "typ": "JWT"}
    return ".".join([_b64(json.dumps(header).encode()), _b64(json.dumps(payload).encode()), _b64(b"signature")])


def _http(pap, method, path, body=None):
    req = urllib.request.Request(
        pap + path,
        method=method,
        data=None if body is None else json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req) as r:
        return r.read()


def reset(pap):
    for p in json.loads(_http(pap, "GET", "/policy")):
        _http(pap, "DELETE", f"/policy/{p['id']}")


def download(pap, out):
    for bundle in ("policies", "methods", "data"):
        raw = _http(pap, "GET", f"/bundles/service/v1/{bundle}.tar.gz")
        with tarfile.open(fileobj=io.BytesIO(raw), mode="r:gz") as tar:
            tar.extractall(out / bundle, filter="data")
        (out / bundle / ".manifest").unlink()
    # OPA loads a directory's data.json at the directory's path: the data bundle's
    # root ({"data": {...}}) must sit at the top, as in the connector's OPA.
    (out / "data" / "data.json").rename(out / "data.json")
    (out / "data").rmdir()


def opa_input(req, offer, others):
    who = {"buyer": buyer_of(offer["name"]), "stranger": STRANGER, "other_buyer": others[0] if others else None}
    headers = dict(req["headers"])
    issuer = who.get(req["who"]) if req["who"] else None
    if req["who"] and issuer is None:
        return None  # no other offer on this provider: case does not apply
    if issuer:
        roles = [offer["role"]] if req["roles"] is None else req["roles"]
        headers["authorization"] = "Bearer " + token(issuer, req["cred"] or offer["credential"], roles)
    request = {"method": req["method"], "path": req["path"], "headers": headers, "query": req["query"]}
    if req["body"] is not None:
        request["body"] = req["body"]
    return {"request": request}


def rego_name(text):
    return re.sub(r"[^A-Za-z0-9_]", "_", text)


def tests_for(provider_id, offers):
    lines = [
        "# Generated by tests/opa/build.py from tests/opa/cases.py: do not edit.",
        f"package cases_test.{rego_name(provider_id)}",
        "",
        "import rego.v1",
        "",
    ]
    count = 0
    for offer in offers:
        others = [buyer_of(o["name"]) for o in offers if o["name"] != offer["name"]]
        for name, expected, req in CASES[offer["class"]](offer):
            inp = opa_input(req, offer, others)
            if inp is None:
                continue
            check = "not data.policy.main.allow" if expected == "deny" else "data.policy.main.allow"
            prefix = "GAP_" if expected == "gap" else ""
            lines += [
                f"# {offer['class']}: {expected}",
                f"test_{prefix}{rego_name(offer['name'])}__{name} if {{",
                f"\t{check} with input as {json.dumps(inp)}",
                "}",
                "",
            ]
            count += 1
    return "\n".join(lines), count


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pap", default="http://localhost:18080")
    ap.add_argument("--out", default="tests/opa/out")
    ap.add_argument("--offers", default="offers")
    args = ap.parse_args()

    generated = generate(args.offers)
    out_root = pathlib.Path(args.out)
    shutil.rmtree(out_root, ignore_errors=True)
    for provider, offers in load_offers(args.offers):
        reset(args.pap)
        for offer in offers:
            chars = generated[(provider["id"], offer["name"])]
            odrl = next(c for c in chars if c["name"] == "ODRL policy")
            policy = odrl["productSpecCharacteristicValue"][0]["value"][0]
            pid = rego_name(f"order_{offer['name']}").lower()
            _http(args.pap, "PUT", f"/policy/{pid}", instantiate(policy, buyer_of(offer["name"]), pid))
        out = out_root / provider["id"]
        download(args.pap, out)
        text, n = tests_for(provider["id"], offers)
        (out / "cases_test.rego").write_text(text)
        print(f"{provider['id']}: {len(offers)} policies, {n} cases -> {out}")
    reset(args.pap)


if __name__ == "__main__":
    main()
